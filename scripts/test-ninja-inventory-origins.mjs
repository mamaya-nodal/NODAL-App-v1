import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
const owner='00000000-0000-0000-0000-000000000001';
const personal='00000000-0000-0000-0000-000000000002';
const identity='00000000-0000-0000-0000-000000000003';
const other='00000000-0000-0000-0000-000000000004';
await db.exec(`create schema auth;
create function auth.uid() returns uuid language sql as $$select '${owner}'::uuid$$;
create function public.is_current_user_active() returns boolean language sql as $$select true$$;
create table ninja_connectors(id uuid primary key,owner_user_id uuid,status text);
create table ninja_inventory_snapshots(connector_id uuid,physical_connector_id uuid,observed_at timestamptz,accounts jsonb);
create table ninja_connector_connection_reviews(connector_id uuid,connection_name text,status text);
create table ninja_broker_account_exclusions(owner_user_id uuid,account_name text);
insert into ninja_connectors values('${personal}','${owner}','active'),('${identity}','${owner}','active'),('${other}','${other}','active');`);
const account=(name,cash=50000)=>({accountName:name,connectionName:'Ninja',cashValue:cash});
const insert=async(dest,source,at,accounts)=>db.query('insert into ninja_inventory_snapshots values($1,$2,$3,$4)',[dest,source,at,JSON.stringify(accounts)]);
await insert(personal,personal,'2026-11-14T21:00Z',[account('broker'),account('own-prop')]);
await insert(personal,identity,'2026-11-14T21:01Z',[account('broker',51000)]);
await insert(identity,identity,'2026-11-14T21:01Z',[account('identity-prop')]);
await insert(other,other,'2026-11-14T21:02Z',[account('PRIVATE-OTHER-USER')]);
await db.exec(await readFile(new URL('../supabase/migrations/20261114222000_ninja_inventory_per_physical_origin.sql',import.meta.url),'utf8'));
let result=(await db.query('select * from get_current_user_ninja_inventory()')).rows;
assert.equal(result.length,2,'owner scope');
let own=result.find(r=>r.connector_id===personal);
assert.deepEqual(own.accounts.map(a=>a.accountName).sort(),['broker','own-prop'],'identity fragment cannot hide personal prop');
assert.equal(own.accounts.find(a=>a.accountName==='broker').cashValue,51000,'latest duplicate economic observation wins');
assert.equal(Date.parse(own.accounts.find(a=>a.accountName==='broker').firstSeenAt),Date.parse('2026-11-14T21:00:00Z'),'first seen retained');
await insert(personal,personal,'2026-11-14T21:03Z',[]);
own=(await db.query('select * from get_current_user_ninja_inventory()')).rows.find(r=>r.connector_id===personal);
assert.deepEqual(own.accounts.map(a=>a.accountName),['broker'],'empty snapshot clears only its own source');
await db.query('insert into ninja_broker_account_exclusions values($1,$2)',[owner,'broker']);
own=(await db.query('select * from get_current_user_ninja_inventory()')).rows.find(r=>r.connector_id===personal);
assert.equal(own.accounts.length,0,'explicit exclusions preserved');
await db.query('insert into ninja_connector_connection_reviews values($1,$2,$3)',[identity,'Ninja','isolated']);
const isolated=(await db.query('select * from get_current_user_ninja_inventory()')).rows.find(r=>r.connector_id===identity);
assert.equal(isolated.accounts.length,0,'isolated connections preserved');
await db.close();
console.log('7 inventory-origin checks passed');
